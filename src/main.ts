/**
 * Entry point. Builds the Phaser game (640x360, nearest-neighbour scaling) and
 * registers every scene. `BootScene` is first, so it runs automatically.
 */

import Phaser from 'phaser';
import { DEBUG_ENABLED, VIEW_H, VIEW_W } from './config/constants';
import { GameApp } from './core/GameApp';
import { session } from './core/Session';
import { BattleScene } from './scenes/BattleScene';
import { BootScene } from './scenes/BootScene';
import { EndScene } from './scenes/EndScene';
import { OverlayScene } from './scenes/OverlayScene';
import { StoryScene } from './scenes/StoryScene';
import { TitleScene } from './scenes/TitleScene';
import { WorldScene } from './scenes/WorldScene';

/** Surfaces fatal errors inside the frame instead of a blank canvas. */
function reportFailure(message: string): void {
  const el = document.getElementById('boot-error');
  if (!el) return;
  el.style.display = 'flex';
  el.textContent = message;
}

window.addEventListener('error', (e) => reportFailure(String(e.message ?? e.error)));
window.addEventListener('unhandledrejection', (e) => reportFailure(String(e.reason)));

if (!document.getElementById('game-container')) {
  reportFailure('Missing #game-container in index.html.');
} else {
  try {
    const game = new GameApp({
      type: Phaser.AUTO,
      parent: 'game-container',
      width: VIEW_W,
      height: VIEW_H,
      backgroundColor: '#0b0f1a',
      pixelArt: true,
      roundPixels: true,
      // Sound is generated by src/audio/Audio.ts, so Phaser's own audio is off.
      audio: { noAudio: true },
      scale: {
        mode: Phaser.Scale.FIT,
        autoCenter: Phaser.Scale.CENTER_BOTH
      },
      render: {
        antialias: false,
        pixelArt: true,
        roundPixels: true
      },
      scene: [BootScene, TitleScene, StoryScene, WorldScene, BattleScene, OverlayScene, EndScene]
    });

    if (DEBUG_ENABLED) {
      // `?debug=1` hands the game and the run state to the console (and to
      // scripts/e2e.mjs, which needs to jump straight into a battle).
      const w = window as unknown as { game: Phaser.Game; session: typeof session };
      w.game = game;
      w.session = session;
    }
  } catch (err) {
    reportFailure(`Could not start the game: ${String(err)}`);
  }
}
